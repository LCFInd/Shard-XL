"""Rasterize Inter Tight (OFL, assets/fonts) into src/font_data.h: alpha atlases for the UI's text sizes,
at 1x and 2x (the Mac's Retina screens). Run from the repository root:  python3 tools/gen_font.py"""
from PIL import Image, ImageDraw, ImageFont

TTF = 'assets/fonts/InterTight.ttf'
SIZES = [(11, 500), (13, 500), (15, 600), (18, 600), (24, 700), (9, 600)]   # (pixel size at 1x, weight); append only
EXTRA = [0xB7, 0x2013, 0xD7, 0xB5, 0xB0, 0x2192, 0x2190, 0x25B6, 0x25CF, 0x2026]   # · – × µ ° → ← ▶ ● …
CODES = list(range(32, 127)) + EXTRA

out = ['/* SPDX-License-Identifier: GPL-3.0-only */',
       '/* Generated by tools/gen_font.py from Inter Tight (SIL Open Font License, assets/fonts/OFL.txt). Do not edit. */',
       '#pragma once', '#include <stdint.h>',
       'typedef struct { uint16_t x, y; uint8_t w, h; int8_t xo, yo; uint8_t adv; } xl_glyph;',
       'typedef struct { int px, ascent, height, aw, ah; const xl_glyph *g; const uint8_t *a; } xl_font;',
       f'#define XL_NFONT {len(SIZES)}', f'#define XL_NGLYPH {len(CODES)}',
       'static const uint32_t XL_CODES[XL_NGLYPH] = {' + ','.join(str(c) for c in CODES) + '};']
fonts = []
for scale in (1, 2):
    for i, (px, wt) in enumerate(SIZES):
        f = ImageFont.truetype(TTF, px * scale)
        f.set_variation_by_axes([wt])
        asc, desc = f.getmetrics()
        glyphs = []
        for c in CODES:
            ch = chr(c)
            bb = f.getbbox(ch)
            adv = round(f.getlength(ch))
            w, h = max(0, bb[2] - bb[0]), max(0, bb[3] - bb[1])
            im = Image.new('L', (max(1, w), max(1, h)), 0)
            if w and h:
                ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=f, fill=255)
            glyphs.append((c, im, w, h, bb[0], bb[1], adv))
        # pack in rows
        aw = 512 * scale
        x = y = rowh = 0
        place = []
        for g in glyphs:
            w, h = g[2], g[3]
            if x + w + 1 > aw:
                x, y, rowh = 0, y + rowh + 1, 0
            place.append((x, y))
            x += w + 1
            rowh = max(rowh, h)
        ah = y + rowh + 1
        atlas = Image.new('L', (aw, ah), 0)
        for g, (gx, gy) in zip(glyphs, place):
            if g[2] and g[3]:
                atlas.paste(g[1], (gx, gy))
        name = f'f{scale}_{i}'
        data = atlas.tobytes()
        out.append(f'static const uint8_t {name}_a[{len(data)}] = {{' + ','.join(str(b) for b in data) + '};')
        out.append(f'static const xl_glyph {name}_g[XL_NGLYPH] = {{' + ','.join(
            f'{{{gx},{gy},{g[2]},{g[3]},{g[4]},{g[5]},{g[6]}}}' for g, (gx, gy) in zip(glyphs, place)) + '};')
        fonts.append(f'{{{px*scale},{asc},{asc+desc},{aw},{ah},{name}_g,{name}_a}}')
out.append('static const xl_font XL_FONTS[2][XL_NFONT] = {{' + ','.join(fonts[:len(SIZES)]) + '},{' +
           ','.join(fonts[len(SIZES):]) + '}};')
open('src/font_data.h', 'w').write('\n'.join(out) + '\n')
print('src/font_data.h written')
